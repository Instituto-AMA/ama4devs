const rawSpec = await readSpec()
const { spec, applied } = applyOverlays(rawSpec)
console.log(`Applied overlays: ${applied.join(', ') || '(none)'}`)

const SCHEMAS = spec.components.schemas as Record<string, any>

// ───────────────────────────────────────────────────────────── enums: deduplicate

interface EnumGroup {
  name: string
  values: string[]
  /** Original names in the specification that collapsed into this group. */
  aliases: string[]
}

const byValueSet = new Map<string, string[]>()
for (const [name, schema] of Object.entries(SCHEMAS)) {
  if (!Array.isArray(schema.enum)) continue
  const key = stableStringify([...schema.enum].sort())
  const list = byValueSet.get(key) ?? []
  list.push(name)
  byValueSet.set(key, list)
}

const enumGroups: EnumGroup[] = []
const takenEnumNames = new Set<string>()

// Two DIFFERENT value sets can derive the same canonical name — and they do:
// "PaymentStatus" comes both from the 14-value enum (the real charge status) and
// from a 4-value enum used only in the statistics filter. The one with more aliases
// is the main concept and keeps the short name; the loser falls back to its
// original name, which is unique by construction.
const candidateGroups = [...byValueSet.values()]
  .map((aliases) => ({
    aliases,
    values: SCHEMAS[aliases[0]!].enum as string[],
    candidate: [...aliases]
      .map(enumNameCandidate)
      .sort((a, b) => a.length - b.length || a.localeCompare(b))[0]!,
  }))
  .sort(
    (a, b) =>
      b.aliases.length - a.aliases.length ||
      a.candidate.localeCompare(b.candidate) ||
      a.aliases[0]!.localeCompare(b.aliases[0]!),
  )

for (const g of candidateGroups) {
  let name = g.candidate
  if (takenEnumNames.has(name)) {
    name = [...g.aliases].sort((a, b) => a.length - b.length || a.localeCompare(b))[0]!
  }
  if (takenEnumNames.has(name)) throw new Error(`Irreparable enum name collision: ${name}`)
  takenEnumNames.add(name)
  enumGroups.push({ name, values: g.values, aliases: g.aliases })
}
enumGroups.sort((a, b) => a.name.localeCompare(b.name))

/** the spec's original name → the enum's canonical name */
const enumAliasMap = new Map<string, string>()
for (const g of enumGroups) for (const a of g.aliases) enumAliasMap.set(a, g.name)

console.log(
  `Enums: ${enumAliasMap.size} in the spec → ${enumGroups.length} canonical ` +
    `(${enumAliasMap.size - enumGroups.length} duplicates collapsed)`,
)

// ───────────────────────────────────────────────────────────── grafo de refs

const isEnum = (n: string) => enumAliasMap.has(n)

function refsOf(node: any, out = new Set<string>()): Set<string> {
  if (!node || typeof node !== 'object') return out
  if (Array.isArray(node)) {
    for (const n of node) refsOf(n, out)
    return out
  }
  if (typeof node.$ref === 'string') {
    const name = node.$ref.split('/').pop()!
    out.add(name)
  }
  for (const [k, v] of Object.entries(node)) {
    if (k === '$ref') continue
    refsOf(v, out)
  }
  return out
}

/** The transitive closure of refs from a schema. */
function reachable(start: Iterable<string>): Set<string> {
  const seen = new Set<string>()
  const stack = [...start]
  while (stack.length) {
    const name = stack.pop()!
    if (seen.has(name) || !SCHEMAS[name]) continue
    seen.add(name)
    for (const r of refsOf(SCHEMAS[name])) stack.push(r)
  }
  return seen
}

// ───────────────────────────────────────────────────────────── operations

interface Op {
  operationId: string
  tag: string
  method: HttpMethod
  specPath: string
  elysiaPath: string
  /** Filled in when this operation shares a route with another one (see the normalization below). */
  variantOf?: string
  summary?: string
  pathParams: { name: string; schema: any }[]
  queryParams: { name: string; schema: any; required: boolean }[]
  bodyRef?: string
  bodyContentType?: 'application/json' | 'multipart/form-data'
  responses: { status: number; ref?: string }[]
}

const ops: Op[] = []
const seenOpIds = new Set<string>()

for (const { path: rawPath, method, op } of eachOperation(spec)) {
  if (!op.operationId) throw new Error(`Operation without an operationId: ${method} ${rawPath}`)
  if (seenOpIds.has(op.operationId)) {
    throw new Error(`Duplicated operationId in the spec: ${op.operationId}`)
  }
  seenOpIds.add(op.operationId)

  /**
   * The spec has 13 paths with a SPURIOUS TRAILING SLASH. In 5 of them there is a
   * twin without the slash and with the same method:
   *
   *   POST /v3/payments    → create a charge
   *   POST /v3/payments/   → create a charge with a credit card
   *
   * In the real Asaas that is ONE endpoint — the slash is an artifact of the
   * documentation, used to separate two pages. Worse: the empty segment corrupts
   * the route tree's node and takes down the neighbouring GET.
   *
   * We normalize the slash. Both operationIds stay in the manifest (the client may
   * call either one), but only the canonical one registers a route — the variant
   * is flagged with `variantOf`, and the handler decides by the body, as Asaas does.
   */
  const path = rawPath.length > 1 ? rawPath.replace(/\/$/, '') : rawPath

  const tag = op.tags?.[0] ?? 'Untagged'
  const params = op.parameters ?? []

  const bodyContent = op.requestBody?.content ?? {}
  const bodyContentType = ('application/json' in bodyContent
    ? 'application/json'
    : 'multipart/form-data' in bodyContent
      ? 'multipart/form-data'
      : undefined) as Op['bodyContentType']
  const bodySchema = bodyContentType ? bodyContent[bodyContentType]?.schema : undefined

  const responses: Op['responses'] = []
  for (const [status, res] of Object.entries(op.responses ?? {})) {
    const code = Number(status)
    if (!Number.isFinite(code)) continue
    const schema = (res as any)?.content?.['application/json']?.schema
    responses.push({ status: code, ref: schema?.$ref?.split('/').pop() })
  }

  /**
   * The spec's parameter names COLLIDE between sibling routes:
   *   /v3/paymentLinks/{id}/images
   *   /v3/paymentLinks/{paymentLinkId}/images/{imageId}
   * The router refuses two different names in the same position. We normalize to
   * :p0, :p1… and keep the real names in `paramNames` — the register remaps them
   * before calling the handler, which keeps seeing `params.paymentLinkId`.
   */
  let paramIndex = 0
  const elysiaPath = path.replace(/\{[^}]+\}/g, () => `:p${paramIndex++}`)

  ops.push({
    operationId: op.operationId,
    tag,
    method,
    specPath: path,
    elysiaPath,
    summary: op.summary,
    pathParams: params
      .filter((p: any) => p.in === 'path')
      .map((p: any) => ({ name: p.name, schema: p.schema })),
    queryParams: params
      .filter((p: any) => p.in === 'query')
      .map((p: any) => ({ name: p.name, schema: p.schema, required: !!p.required })),
    bodyRef: bodySchema?.$ref?.split('/').pop(),
    bodyContentType,
    responses: responses.sort((a, b) => a.status - b.status),
    // used only below, to pick the canonical operation of each route
    ...({ hadTrailingSlash: rawPath.length > 1 && rawPath.endsWith('/') } as object),
  })
}
ops.sort((a, b) => a.operationId.localeCompare(b.operationId))

// Flags the variants that share a route with another operation.
const byRoute = new Map<string, Op[]>()
for (const op of ops) {
  const key = `${op.method} ${op.elysiaPath}`
  byRoute.set(key, [...(byRoute.get(key) ?? []), op])
}
let variantCount = 0
for (const [key, group] of byRoute) {
  if (group.length === 1) continue
  // The canonical one is the one that did NOT have a trailing slash in the spec.
  const canonical =
    group.find((o) => !(o as unknown as { hadTrailingSlash: boolean }).hadTrailingSlash) ??
    group[0]!
  for (const op of group) {
    if (op === canonical) continue
    op.variantOf = canonical.operationId
    variantCount++
    console.log(`  variant: ${op.operationId}\n            shares "${key}" with ${canonical.operationId}`)
  }
}
if (variantCount) console.log(`Shared routes: ${variantCount} variants\n`)

const tags = [...new Set(ops.map((o) => o.tag))].sort()
console.log(`Operations: ${ops.length} in ${tags.length} tags`)

// ───────────────────────────────────────────────────────────── particionamento

// Which schemas each tag reaches. Reached by 1 tag → it lives in that tag's file.
// Reached by 2+ → common.ts. That guarantees no tag file has to import from
// another tag file (no cyclic import between tags).
const tagsOfSchema = new Map<string, Set<string>>()

for (const op of ops) {
  const roots = new Set<string>()
  if (op.bodyRef) roots.add(op.bodyRef)
  for (const r of op.responses) if (r.ref) roots.add(r.ref)
  for (const p of [...op.pathParams, ...op.queryParams]) {
    for (const r of refsOf(p.schema)) roots.add(r)
  }
  for (const name of reachable(roots)) {
    if (isEnum(name)) continue
    const set = tagsOfSchema.get(name) ?? new Set()
    set.add(op.tag)
    tagsOfSchema.set(name, set)
  }
}

const fileOfSchema = new Map<string, string>() // nome do schema → 'common' | tagFile
for (const name of Object.keys(SCHEMAS)) {
  if (isEnum(name)) continue
  const owners = tagsOfSchema.get(name)
  if (!owners || owners.size !== 1) {
    fileOfSchema.set(name, 'common') // orphan or shared
  } else {
    fileOfSchema.set(name, tagToFile([...owners][0]!))
  }
}

const grouped = new Map<string, string[]>()
for (const [name, file] of fileOfSchema) {
  const list = grouped.get(file) ?? []
  list.push(name)
  grouped.set(file, list)
}

// ───────────────────────────────────────────────────────────── emissor TypeBox

/**
 * The spec NEVER declares `nullable`, but Asaas's API returns `null` in dozens of
 * fields (originalValue, paymentDate, creditCard…). Validating the response to
 * the letter would reject a legitimate response. Rule: a `required` field is
 * strict; an optional field accepts null. It still catches a wrong type, an
 * invalid enum and a missing field — which is what the contract validation needs
 * to catch.
 */
function emit(schema: any, currentFile: string, indent = 2): string {
  const pad = ' '.repeat(indent)

  if (schema.$ref) {
    const raw = schema.$ref.split('/').pop()!
    if (isEnum(raw)) return enumAliasMap.get(raw)!
    return schemaName(raw)
  }

  const opts: string[] = []
  if (schema.description) opts.push(`description: ${JSON.stringify(schema.description)}`)
  if (schema.example !== undefined) opts.push(`examples: [${JSON.stringify(schema.example)}]`)
  const withOpts = (expr: string) => {
    if (!opts.length) return expr
    const o = `{ ${opts.join(', ')} }`
    return expr.endsWith('()') ? `${expr.slice(0, -1)}${o})` : `${expr.slice(0, -1)}, ${o})`
  }

  /**
   * WATCH THE ORDER: `type` is tested BEFORE `enum`.
   *
   * Asaas's spec has fields declared as `type: 'array'` that ALSO carry an `enum`
   * at the array level (the correct enum is already in `items.$ref`). E.g. the
   * webhook's `events`, the checkout's `billingTypes`.
   *
   * If we tested `enum` first, those fields would become `Type.Union([…])` — a
   * single value instead of a list — and the contract validation would reject a
   * perfectly legitimate response. It was a real bug, found by track B.
   */
  if (schema.type === undefined && Array.isArray(schema.enum)) {
    const vals = schema.enum.map((v: string) => `Type.Literal(${JSON.stringify(v)})`)
    return `Type.Union([${vals.join(', ')}])`
  }

  if (schema.type === 'string' && Array.isArray(schema.enum)) {
    const vals = schema.enum.map((v: string) => `Type.Literal(${JSON.stringify(v)})`)
    return `Type.Union([${vals.join(', ')}])`
  }

  switch (schema.type) {
    case 'string':
      if (schema.format === 'binary') return 'Type.Any()'
      return withOpts('Type.String()')
    case 'integer':
      return withOpts('Type.Integer()')
    case 'number':
      return withOpts('Type.Number()')
    case 'boolean':
      return withOpts('Type.Boolean()')
    case 'array':
      return `Type.Array(${emit(schema.items ?? {}, currentFile, indent)})`
    case 'object':
    case undefined: {
      const props = schema.properties as Record<string, any> | undefined
      if (!props) return 'Type.Any()'
      const required = new Set<string>(schema.required ?? [])
      const lines: string[] = []
      for (const [key, prop] of Object.entries(props)) {
        const inner = emit(prop, currentFile, indent + 2)
        const wrapped = required.has(key) ? inner : `Type.Optional(Nullable(${inner}))`
        lines.push(`${pad}  ${JSON.stringify(key)}: ${wrapped},`)
      }
      if (!lines.length) return 'Type.Object({})'
      return `Type.Object({\n${lines.join('\n')}\n${pad}})`
    }
    default:
      return 'Type.Any()'
  }
}

/** Sorts declarations by dependency — TypeBox uses `const`, it has to be declared before being used. */
function topoSort(names: string[], file: string): string[] {
  const inFile = new Set(names)
  const state = new Map<string, 'visiting' | 'done'>()
  const out: string[] = []

  const visit = (name: string, trail: string[]) => {
    if (state.get(name) === 'done') return
    if (state.get(name) === 'visiting') {
      throw new Error(
        `Reference cycle in ${file}: ${[...trail, name].join(' → ')}.\n` +
          `TypeBox would need Type.Recursive here — the codegen does not support it yet.`,
      )
    }
    state.set(name, 'visiting')
    for (const dep of refsOf(SCHEMAS[name])) {
      if (inFile.has(dep)) visit(dep, [...trail, name])
    }
    state.set(name, 'done')
    out.push(name)
  }

  for (const n of [...names].sort()) visit(n, [])
  return out
}

