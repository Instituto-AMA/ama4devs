/**
 * Codegen: Asaas's OpenAPI spec → TypeBox + the operations manifest.
 *
 *   bun run codegen
 *
 * What comes out of here (everything in src/generated/, all committed, nothing
 * hand-edited):
 *
 *   enums.ts        The spec's 173 enums, DEDUPLICATED by their value set.
 *                   (Asaas emits one enum schema per operation: there are 7
 *                   different "PaymentStatus" with identical values.)
 *   schemas/*.ts    TypeBox, one file per tag + common.ts for the shared ones.
 *   operations.ts   The MANIFEST of the 213 operations. It is the backbone of the
 *                   project: the routes are registered by iterating it, and every
 *                   operationId without a handler falls into an automatic
 *                   notImplemented. That way "the 213 routes exist" is a build
 *                   invariant, not a checklist.
 */
