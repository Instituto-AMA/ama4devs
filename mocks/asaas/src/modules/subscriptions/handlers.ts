/**
 * Subscription — the 13 operations. (Track E)
 *
 * THE CENTRAL RULE, and it cost a lot to find out:
 *
 *   **creating the subscription ALREADY CREATES the first charge.**
 *
 * Reading the documentation, we had concluded the opposite — that the charge
 * would only be born when the due date entered the 40-day window, and that the
 * POST created nothing. This file once ASSERTED that, in capital letters, with
 * a warning to nobody "fix" it. It was wrong.
 *
 * The capture against the real sandbox (`bun run capture`) proved:
 *
 *   POST /v3/subscriptions with nextDueDate = today+60
 *     → the answer brings nextDueDate = today+90  (it already moved one cycle)
 *     → and the charge due today+60 ALREADY EXISTS
 *
 * The 40-day window (`subscriptionLookaheadDays`) governs the FOLLOWING
 * charges, generated by the scheduler. The first one belongs to the POST.
 *
 * It is recorded here as a caution: a confident wrong comment is worse than no
 * comment, because it stops the next person from doubting it.
 */
